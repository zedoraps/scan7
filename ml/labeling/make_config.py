"""Generate ml/labeling/label_config.xml from ml/config/cards.yaml (class order = YOLO ids).

    uv run --project ml python ml/labeling/make_config.py

Re-run after changing cards.yaml, then re-run setup_projects.py to push the config.
"""

from __future__ import annotations

from xml.sax.saxutils import quoteattr

from lsutil import HINT_NAME, FROM_NAME, LABEL_CONFIG, TO_NAME, load_classes

# 23+ visually distinct colors (cycled if more classes are ever added).
PALETTE = [
    "#e6194b", "#3cb44b", "#ffe119", "#4363d8", "#f58231", "#911eb4", "#46f0f0", "#f032e6",
    "#bcf60c", "#fabebe", "#008080", "#9a6324", "#800000", "#aaffc3", "#808000", "#ffd8b1",
    "#000075", "#808080", "#ff4500", "#00bfff", "#ffd700", "#dc143c", "#2f4f4f", "#7fff00",
]

# Hotkeys chosen to avoid Label Studio's built-in single-key shortcuts (b, e, h, k, m, o, p, r, u, v, w).
HOTKEYS = {
    "00": "0", "01": "1", "02": "2", "03": "3", "04": "4", "05": "5", "06": "6", "07": "7",
    "08": "8", "09": "9", "10": "q", "11": "i", "12": "l",
    "plus2": "a", "plus4": "s", "plus6": "d", "plus8": "f", "plus10": "g", "x2": "x",
    "freeze": "z", "flip3": "t", "second_chance": "c", "back": "n",
}


def build(classes: list[str]) -> str:
    lines = [
        "<!-- GENERATED by ml/labeling/make_config.py from ml/config/cards.yaml. Do not edit by hand. -->",
        "<View>",
        f'  <Image name="{TO_NAME}" value="$image" zoom="true" zoomControl="true" rotateControl="false"/>',
        f'  <RectangleLabels name="{FROM_NAME}" toName="{TO_NAME}" strokeWidth="2" canRotate="false">',
    ]
    used = set()
    for i, c in enumerate(classes):
        attrs = f'value={quoteattr(c)} background="{PALETTE[i % len(PALETTE)]}"'
        hk = HOTKEYS.get(c)
        if hk and hk not in used:
            used.add(hk)
            attrs += f' hotkey="{hk}"'
        lines.append(f"    <Label {attrs}/>  <!-- id {i} -->")
    lines += [
        "  </RectangleLabels>",
        # Hints from the app scan check (ml/labeling/app_scans.py): e.g. "missing: 07 - draw its box".
        # Free text, ignored by export_yolo.py.
        f'  <Header value="Hint" size="6"/>',
        f'  <TextArea name="{HINT_NAME}" toName="{TO_NAME}" rows="2" editable="true" maxSubmissions="1"/>',
        "</View>",
        "",
    ]
    return "\n".join(lines)


def main():
    classes = load_classes()
    LABEL_CONFIG.write_text(build(classes))
    print(f"Wrote {LABEL_CONFIG} with {len(classes)} classes")


if __name__ == "__main__":
    main()
