#!/usr/bin/env bash
# Start Label Studio for scan7 real-photo labeling on http://localhost:8080
#
# - All state (SQLite DB, media, exports, credentials) lives in ml/labeling/ls_data/ (gitignored).
# - Photos are served read-only from ml/data via Local Files storage.
# - On first start a local admin user is created non-interactively; the password and
#   API token are written to ml/labeling/ls_data/credentials.txt.
#
# Label Studio itself is installed as an isolated uv tool (not part of ml/pyproject.toml):
#   uv tool install --python 3.12 label-studio
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ML_DIR="$(cd "$HERE/.." && pwd)"
DATA_DIR="$HERE/ls_data"
CREDS="$DATA_DIR/credentials.txt"
PORT="${LS_PORT:-8080}"

LS_BIN="$(command -v label-studio || true)"
[ -z "$LS_BIN" ] && [ -x "$HOME/.local/bin/label-studio" ] && LS_BIN="$HOME/.local/bin/label-studio"
if [ -z "$LS_BIN" ]; then
  echo "label-studio not found. Install it with: uv tool install --python 3.12 label-studio" >&2
  exit 1
fi

mkdir -p "$DATA_DIR"
chmod 700 "$DATA_DIR"

if [ ! -f "$CREDS" ]; then
  umask 077
  {
    echo "# Label Studio local admin for scan7 (generated by start.sh). Do not commit."
    echo "LS_URL=http://localhost:$PORT"
    echo "LS_EMAIL=admin@scan7.local"
    echo "LS_PASSWORD=$(openssl rand -base64 18 | tr -d '/+=' | cut -c1-20)"
    echo "LS_TOKEN=$(openssl rand -hex 20)"
  } > "$CREDS"
  echo "Created new credentials in $CREDS"
fi

# shellcheck disable=SC1090
source "$CREDS"

export LABEL_STUDIO_BASE_DATA_DIR="$DATA_DIR"
export LABEL_STUDIO_LOCAL_FILES_SERVING_ENABLED=true
export LABEL_STUDIO_LOCAL_FILES_DOCUMENT_ROOT="$ML_DIR/data"
# No analytics / update checks.
export COLLECT_ANALYTICS=false
export LABEL_STUDIO_COLLECT_ANALYTICS=false
export LABEL_STUDIO_LATEST_VERSION_CHECK=false
# Default user, created on first start only (passed via env so it never shows up in `ps`).
export LABEL_STUDIO_USERNAME="$LS_EMAIL"
export LABEL_STUDIO_PASSWORD="$LS_PASSWORD"
export LABEL_STUDIO_USER_TOKEN="$LS_TOKEN"

echo "Label Studio: http://localhost:$PORT  (login: see $CREDS)"
exec "$LS_BIN" start \
  --data-dir "$DATA_DIR" \
  --internal-host 127.0.0.1 \
  --port "$PORT" \
  --no-browser \
  --enable-legacy-api-token \
  "$@"
